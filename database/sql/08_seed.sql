-- Reserva pagada de ejemplo
DECLARE
    V_ID_USUARIO  NUMBER;
    V_ID_FUNCION  NUMBER;
    V_ID_ASIENTO1 NUMBER;
    V_ID_ASIENTO2 NUMBER;
    V_ID_RESERVA  NUMBER;
    V_CODIGO      VARCHAR2(30);
    V_TOTAL       NUMBER;
    V_ID_PAGO     NUMBER;
    V_COD_PAGO    VARCHAR2(50);
    V_ASIENTOS    T_LISTA_ID;
BEGIN
    SELECT ID_USUARIO INTO V_ID_USUARIO FROM USUARIO WHERE CORREO = 'juan@email.com';

    SELECT ID_FUNCION INTO V_ID_FUNCION FROM (
        SELECT F.ID_FUNCION
        FROM   FUNCION F
        JOIN   PELICULA P ON P.ID_PELICULA = F.ID_PELICULA
        WHERE  P.TITULO = 'Intensamente 2'
        ORDER BY F.FECHA_HORA
    ) WHERE ROWNUM = 1;

    SELECT ID_ASIENTO INTO V_ID_ASIENTO1
    FROM   ASIENTO WHERE FILA = 'A' AND NUMERO = 1
      AND  ID_SALA = (SELECT ID_SALA FROM FUNCION WHERE ID_FUNCION = V_ID_FUNCION);

    SELECT ID_ASIENTO INTO V_ID_ASIENTO2
    FROM   ASIENTO WHERE FILA = 'A' AND NUMERO = 2
      AND  ID_SALA = (SELECT ID_SALA FROM FUNCION WHERE ID_FUNCION = V_ID_FUNCION);

    V_ASIENTOS := T_LISTA_ID(V_ID_ASIENTO1, V_ID_ASIENTO2);

    SP_CREAR_RESERVA(V_ID_USUARIO, V_ID_FUNCION, V_ASIENTOS, V_ID_RESERVA, V_CODIGO, V_TOTAL);
    SP_CONFIRMAR_PAGO(V_ID_RESERVA, 'DEBITO', V_ID_PAGO, V_COD_PAGO);
END;
