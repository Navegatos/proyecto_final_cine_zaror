DECLARE
    V_P1 NUMBER; V_P2 NUMBER; V_P3 NUMBER;
    V_S1 NUMBER; V_S2 NUMBER;
    V_F  NUMBER;
BEGIN
    SELECT ID_PELICULA INTO V_P1 FROM PELICULA WHERE TITULO = 'Intensamente 2';
    SELECT ID_PELICULA INTO V_P2 FROM PELICULA WHERE TITULO = 'Deadpool y Wolverine';
    SELECT ID_PELICULA INTO V_P3 FROM PELICULA WHERE TITULO = 'El Señor de los Anillos';
    SELECT ID_SALA INTO V_S1 FROM SALA WHERE NOMBRE = 'Sala 1';
    SELECT ID_SALA INTO V_S2 FROM SALA WHERE NOMBRE = 'Sala 2';

    SP_CREAR_FUNCION(V_P1, V_S1, SYSTIMESTAMP + INTERVAL '1' DAY + INTERVAL '18' HOUR, 6000, V_F);
    SP_CREAR_FUNCION(V_P1, V_S1, SYSTIMESTAMP + INTERVAL '1' DAY + INTERVAL '21' HOUR, 6000, V_F);
    SP_CREAR_FUNCION(V_P2, V_S2, SYSTIMESTAMP + INTERVAL '2' DAY + INTERVAL '20' HOUR, 8000, V_F);
    SP_CREAR_FUNCION(V_P3, V_S1, SYSTIMESTAMP + INTERVAL '3' DAY + INTERVAL '19' HOUR, 7500, V_F);
    SP_CREAR_FUNCION(V_P3, V_S2, SYSTIMESTAMP + INTERVAL '3' DAY + INTERVAL '22' HOUR, 7500, V_F);
END;
